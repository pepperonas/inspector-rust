#[cfg(test)]
mod tests {
    use super::FONT_5X7;
    #[test]
    fn font_has_95_glyphs_of_five_bits() {
        assert_eq!(FONT_5X7.len(), 95 * 7);
        assert!(FONT_5X7.iter().all(|r| *r < 32));
        // space is empty, 'A' is not
        assert!(FONT_5X7[..7].iter().all(|r| *r == 0));
        assert!(FONT_5X7[(b'A' - 32) as usize * 7..][..7].iter().any(|r| *r != 0));
    }
}
